def seed():
    os.makedirs(os.path.dirname(DATABASE), exist_ok=True)
    db = sqlite3.connect(DATABASE)
    db.row_factory = sqlite3.Row

    # 建表
    with open(os.path.join(BASE_DIR, "app.py"), "r", encoding="utf-8") as f:
        # 只需要建表SQL，通过init_db来建
        pass

    # 直接执行建表
    db.executescript("""
    CREATE TABLE IF NOT EXISTS schools (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL UNIQUE,
        province TEXT, city TEXT, district TEXT,
        latitude REAL, longitude REAL,
        type TEXT, level TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS majors (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        name TEXT NOT NULL, category TEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(name, category)
    );
    CREATE TABLE IF NOT EXISTS reviews (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        school_id INTEGER NOT NULL, major_id INTEGER NOT NULL,
        device_id TEXT NOT NULL,
        professional_difficulty INTEGER, teaching_quality INTEGER,
        college_atmosphere INTEGER, dormitory INTEGER,
        cafeteria INTEGER, campus_environment INTEGER,
        infrastructure INTEGER, employment_prospect INTEGER,
        extracurricular INTEGER, mental_support INTEGER,
        overall_score REAL, comment TEXT, tags TEXT,
        likes INTEGER DEFAULT 0,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (school_id) REFERENCES schools(id),
        FOREIGN KEY (major_id) REFERENCES majors(id),
        UNIQUE(school_id, major_id, device_id)
    );
    CREATE TABLE IF NOT EXISTS comments (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        review_id INTEGER NOT NULL, device_id TEXT NOT NULL,
        content TEXT NOT NULL, likes INTEGER DEFAULT 0,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (review_id) REFERENCES reviews(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS liked_records (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        device_id TEXT NOT NULL,
        target_type TEXT NOT NULL, target_id INTEGER NOT NULL,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(device_id, target_type, target_id)
    );
    """)

    # 插入学校
    for s in SCHOOLS:
        try:
            db.execute(
                "INSERT OR IGNORE INTO schools (name, province, city, district, latitude, longitude, type, level) VALUES (?,?,?,?,?,?,?,?)",
                s
            )
        except Exception as e:
            print(f"插入学校失败: {s[0]}, {e}")

    # 插入专业
    for m in MAJORS:
        try:
            db.execute(
                "INSERT OR IGNORE INTO majors (name, category) VALUES (?,?)",
                m
            )
        except Exception as e:
            print(f"插入专业失败: {m[0]}, {e}")

    db.commit()

    school_count = db.execute("SELECT COUNT(*) FROM schools").fetchone()[0]
    major_count = db.execute("SELECT COUNT(*) FROM majors").fetchone()[0]
    print(f"✅ 种子数据已导入: {school_count} 所学校, {major_count} 个专业")

    db.close()


if __name__ == "__main__":
    seed()
